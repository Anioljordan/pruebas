function normalizeText(text) {
  return text.replace(/\s+/g, " ").trim();
}

function autoBindI18nKeys() {
  document.querySelectorAll("h1, h2, h3, p, span, label, a, button").forEach((element) => {
    if (element.hasAttribute("data-i18n")) return;

    const text = normalizeText(element.textContent);

    if (autoI18nMap[text]) {
      element.setAttribute("data-i18n", autoI18nMap[text]);
    }
  });
}

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.es;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");

    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.documentElement.lang = lang;
  localStorage.setItem("barZemnuLang", lang);

  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  const currentLangName = document.querySelector(".current-lang-name");

  if (currentLangName) {
    currentLangName.textContent = languageLabels[lang] || "Español";
  }
}

document.addEventListener("DOMContentLoaded", () => {
  autoBindI18nKeys();

  const savedLanguage = localStorage.getItem("barZemnuLang") || "es";
  setLanguage(savedLanguage);

  const languageDropdown = document.querySelector(".language-dropdown");
  const languageCurrent = document.querySelector(".language-current");

  if (languageDropdown && languageCurrent) {
    languageCurrent.addEventListener("click", () => {
      const isOpen = languageDropdown.classList.toggle("open");
      languageCurrent.setAttribute("aria-expanded", isOpen);
    });
  }

  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);

      if (languageDropdown && languageCurrent) {
        languageDropdown.classList.remove("open");
        languageCurrent.setAttribute("aria-expanded", "false");
      }
    });
  });

  document.addEventListener("click", (event) => {
    if (
      languageDropdown &&
      languageCurrent &&
      !languageDropdown.contains(event.target)
    ) {
      languageDropdown.classList.remove("open");
      languageCurrent.setAttribute("aria-expanded", "false");
    }
  });

  document.addEventListener("keydown", (event) => {
    if (
      event.key === "Escape" &&
      languageDropdown &&
      languageCurrent
    ) {
      languageDropdown.classList.remove("open");
      languageCurrent.setAttribute("aria-expanded", "false");
    }
  });
});